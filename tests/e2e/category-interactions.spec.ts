import { test, expect, verificationPath } from './fixtures';

test('CATEGORY-03: shared checkbox UI, one whole-category action and editable builtin members', async ({ page, request }) => {
  await page.goto('/');
  const photos = page.getByRole('region', { name: '사진 카테고리', exact: true });
  const master = photos.getByRole('button', { name: '사진 전체 차단', exact: true });
  await expect(master).toBeEnabled();
  await expect(photos.getByRole('checkbox')).toHaveCount(5);
  const title = await photos.getByRole('heading', { name: '사진', exact: true }).boundingBox();
  const count = await photos.getByText('5종 중 0종 차단', { exact: true }).boundingBox();
  expect(count!.x).toBeGreaterThanOrEqual(title!.x + title!.width);
  expect(Math.abs(count!.y - title!.y)).toBeLessThan(6);
  await photos.getByRole('button', { name: '사진 확장자 추가', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '사진 확장자 추가', exact: true });
  const input = dialog.getByRole('textbox', { name: '확장자', exact: true });
  await expect(input).toBeFocused(); await input.fill('.PNG');
  await expect(dialog).toContainText('이미 이 카테고리에 등록된 확장자입니다.');
  await expect(dialog.getByRole('button', { name: '추가', exact: true })).toBeDisabled();
  await input.fill('heic'); await input.press('Enter');
  await expect(dialog).not.toBeVisible();
  await expect(photos.getByRole('checkbox', { name: 'heic', exact: true })).not.toBeChecked();
  await master.click();
  await expect(photos.getByRole('checkbox', { checked: true })).toHaveCount(6);
  await expect(photos.getByRole('button', { name: '사진 전체 허용', exact: true })).toBeVisible();
  await photos.getByRole('checkbox', { name: 'heic', exact: true }).uncheck();
  await expect(photos.getByRole('checkbox')).toHaveCount(6);
  await expect(master).toBeVisible();
  await photos.getByRole('checkbox', { name: 'png', exact: true }).uncheck();
  await photos.getByRole('button', { name: '사진 확장자 제거', exact: true }).click();
  await expect(photos.getByRole('checkbox')).toHaveCount(0);
  const customGif = page.getByRole('button', { name: 'gif 차단 해제', exact: true });
  const categoryGif = photos.getByRole('button', { name: '사진에서 gif 제외', exact: true });
  const chipStyles = (element: Element) => {
    const styles = getComputedStyle(element);
    return Object.fromEntries(['fontSize', 'padding', 'borderRadius', 'borderColor', 'backgroundColor', 'gap', 'height', 'width'].map(key => [key, styles[key as keyof CSSStyleDeclaration]]));
  };
  expect(await customGif.locator('..').evaluate(chipStyles)).toEqual(await categoryGif.locator('..').evaluate(chipStyles));
  expect(await customGif.evaluate(chipStyles)).toEqual(await categoryGif.evaluate(chipStyles));
  await page.locator('.tag-list').screenshot({ path: verificationPath('CATEGORY-05-custom-chips.png') });
  await photos.screenshot({ path: verificationPath('CATEGORY-05-category-chips.png') });
  const remove = photos.getByRole('button', { name: '사진에서 png 제외', exact: true });
  const chip = remove.locator('..');
  const chipBox = await chip.boundingBox();
  const textBox = await chip.getByText('png', { exact: true }).boundingBox();
  const removeBox = await remove.boundingBox();
  expect(removeBox!.x).toBeGreaterThanOrEqual(textBox!.x + textBox!.width);
  expect(removeBox!.x + removeBox!.width).toBeLessThanOrEqual(chipBox!.x + chipBox!.width);
  expect(Math.abs((removeBox!.y + removeBox!.height / 2) - (textBox!.y + textBox!.height / 2))).toBeLessThan(3);
  await photos.screenshot({ path: verificationPath('CATEGORY-04-removal-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await photos.screenshot({ path: verificationPath('CATEGORY-04-removal-mobile.png') });
  await remove.click();
  await expect(photos.getByRole('button', { name: /^사진에서 .* 제외$/ })).toHaveCount(5);
  await photos.getByRole('button', { name: '사진 확장자 제거', exact: true }).click();
  await expect(photos.getByRole('checkbox')).toHaveCount(5);
  await page.reload();
  await expect(photos.getByRole('checkbox', { name: 'heic', exact: true })).toBeVisible();
  await expect(photos.getByRole('checkbox', { name: 'png', exact: true })).toHaveCount(0);
  const data = await (await request.get('/api/policies/categories')).json();
  expect(data.categories.find((c: any) => c.id === 'photos').extensions).toContain('heic');
});

test('CATEGORY-03: category names and deletion use one accessible popup pattern with cancellation', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '카테고리 생성', exact: true }).click();
  let dialog = page.getByRole('dialog', { name: '카테고리 생성', exact: true });
  await dialog.getByRole('textbox', { name: '카테고리 이름', exact: true }).fill('개발');
  await dialog.getByRole('button', { name: '생성', exact: true }).click();
  let group = page.getByRole('region', { name: '개발 카테고리', exact: true });
  await expect(group).toBeVisible();
  await group.getByRole('button', { name: '개발 이름 변경', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '카테고리 이름 변경', exact: true });
  await dialog.getByRole('textbox', { name: '카테고리 이름', exact: true }).fill('도구');
  await dialog.getByRole('button', { name: '저장', exact: true }).click();
  group = page.getByRole('region', { name: '도구 카테고리', exact: true });
  await group.getByRole('button', { name: '도구 카테고리 삭제', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '카테고리 삭제', exact: true });
  await dialog.getByRole('button', { name: '취소', exact: true }).click();
  await expect(group).toBeVisible();
  await group.getByRole('button', { name: '도구 카테고리 삭제', exact: true }).click();
  await dialog.getByRole('button', { name: '삭제', exact: true }).click();
  await expect(group).toHaveCount(0);
  const photos = page.getByRole('region', { name: '사진 카테고리', exact: true });
  await photos.getByRole('button', { name: '사진 확장자 추가', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox').press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(photos.getByRole('button', { name: '사진 확장자 추가', exact: true })).toBeFocused();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: verificationPath('CATEGORY-03-mobile.png'), fullPage: true });
});

test('CATEGORY-03: popup distinguishes policy registration and lost member save keeps recovery guidance', async ({ page, request }) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: '카테고리 생성', exact: true })).toBeEnabled();
  await request.post('/api/policies/custom', { data: { extension: 'zip' } });
  await page.getByRole('button', { name: '정책 새로고침', exact: true }).click();
  const photos = page.getByRole('region', { name: '사진 카테고리', exact: true });
  await photos.getByRole('button', { name: '사진 확장자 추가', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '사진 확장자 추가', exact: true });
  await dialog.getByRole('textbox', { name: '확장자', exact: true }).fill('.ZIP');
  await expect(dialog).toContainText('정책에 이미 등록됨 · 현재 차단.');
  await page.screenshot({ path: verificationPath('CATEGORY-03-popup.png') });
  await page.route('**/api/policies/categories/photos/extensions', async route => {
    const response = await route.fetch(); expect(response.status()).toBe(201); await route.abort('failed');
  });
  await dialog.getByRole('button', { name: '추가', exact: true }).click();
  await expect(dialog).toContainText('카테고리 저장 결과를 확인하지 못했습니다.');
  await expect(dialog.getByRole('textbox')).toHaveValue('.ZIP');
  await dialog.getByRole('button', { name: '취소', exact: true }).click();
  await expect(page.getByText(/카테고리 저장 결과를 확인하지 못했습니다/)).toBeVisible();
  await expect(page.getByRole('button', { name: '파일 선택', exact: true })).toBeDisabled();
  await page.unroute('**/api/policies/categories/photos/extensions');
  await page.getByRole('button', { name: '정책 새로고침', exact: true }).click();
  await expect(photos.getByRole('checkbox', { name: 'zip', exact: true })).toBeChecked();
  await expect(page.getByRole('button', { name: '파일 선택', exact: true })).toBeEnabled();
});
